/**
 * Writes src/env.generated.ts, before every build: the versions of the grids
 * that are installed - shown on the pages and written to the report - and
 * the Infinite Table license key, if there is one (see "License key" in the
 * README). The file is git-ignored.
 *
 * The key is read from INFINITE_LICENSE_KEY, in the environment or in
 * .env.local.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');

function readPackageVersion(name) {
  try {
    const pkg = path.join(ROOT, 'node_modules', name, 'package.json');
    return JSON.parse(fs.readFileSync(pkg, 'utf8')).version;
  } catch {
    return 'unknown';
  }
}

function readLicenseKey() {
  if (process.env.INFINITE_LICENSE_KEY) {
    return process.env.INFINITE_LICENSE_KEY;
  }
  try {
    const env = fs.readFileSync(path.join(ROOT, '.env.local'), 'utf8');
    const match = /^\s*INFINITE_LICENSE_KEY\s*=\s*(.*?)\s*$/m.exec(env);
    return match?.[1].replace(/^(['"])(.*)\1$/, '$2') || '';
  } catch {
    return '';
  }
}

const versions = {
  infinite: readPackageVersion('@infinite-table/infinite-angular'),
  primeng: readPackageVersion('primeng'),
  agGrid: readPackageVersion('ag-grid-community'),
  tanstackTable: readPackageVersion('@tanstack/angular-table'),
  tanstackVirtual: readPackageVersion('@tanstack/angular-virtual'),
  ngZorro: readPackageVersion('ng-zorro-antd'),
};

const file = path.join(ROOT, 'src', 'env.generated.ts');
fs.writeFileSync(
  file,
  `// generated by scripts/write-env.mjs - do not edit, not committed\n` +
    `export const VERSIONS = ${JSON.stringify(versions, null, 2)};\n\n` +
    `export const INFINITE_LICENSE_KEY: string = ${JSON.stringify(
      readLicenseKey(),
    )};\n`,
);
console.log(
  `src/env.generated.ts: ${Object.entries(versions)
    .map(([name, version]) => `${name} ${version}`)
    .join(', ')}${readLicenseKey() ? ', with an Infinite Table license key' : ''}`,
);
